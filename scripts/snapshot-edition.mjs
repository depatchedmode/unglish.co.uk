import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';

const directory = new URL('../assets/editions/a/', import.meta.url);
const source = await readFile(new URL('original.html', directory));
const sourceSHA256 = '6f0d391d5be73349b08559baee80af4d0c7a10ca500033ee2ec5a20fa43c699f';
if (createHash('sha256').update(source).digest('hex') !== sourceSHA256) {
  throw new Error('The archived edition changed. Create a new snapshot rather than replacing edition a.');
}

const html = source.toString('utf8');
const scripts = [...html.matchAll(/<script\b[^>]*>([\s\S]*?)<\/script>/g)].map(match => match[1].trim());
if (scripts.length !== 2) throw new Error('Expected the two original edition scripts.');
const [highlight, artwork] = scripts;

function between(text, start, end) {
  const from = text.indexOf(start);
  const to = text.indexOf(end, from + start.length);
  if (from < 0 || to < 0 || text.indexOf(start, from + start.length) >= 0) {
    throw new Error(`Snapshot extraction marker is absent or ambiguous: ${start}`);
  }
  return text.slice(from, to);
}

const randomFunctions = between(highlight, 'function xmur3(str) {', 'const contractAddress').trim();
const randomMethod = between(highlight, 'random: (...args) => {', 'token: {').trim().replace(/^random: /, '').replace(/,$/, '');
const generator = between(artwork, 'const e=$hl.random', 'let k=null');
const melodyConstants = between(artwork, 'const E=[]', 'let I=!1;');
const melody = between(artwork, '!function(){for(let e=0;e<C;e++)', ',function(){const e="background:');
const borders = between(artwork, 'const $=[', 'let M=0;');
const wordStart = artwork.lastIndexOf('}(function(){') + 2;
const suffix = '())})();';
if (wordStart < 2 || !artwork.endsWith(suffix)) throw new Error('Word generation call could not be isolated.');
const wordFunction = artwork.slice(wordStart, -suffix.length);

const metadata = {
  id: 'unglish-a-6f0d391d5be7',
  edition: 'a',
  sourceSHA256,
  source: './original.html',
  helper: 'Highlight Generative Art Script 0.1.2',
};

const module = `// Generated by scripts/snapshot-edition.mjs from the immutable original.html.
// The original generator, data, random functions, and melody expressions are retained verbatim.
// See PROVENANCE.md for the extraction boundary, input semantics, and licensing status.
export const artifact = Object.freeze(${JSON.stringify(metadata, null, 2)});

${randomFunctions}

function createRandom(hash, tokenId, curated) {
  const seed = curated ? xmur3(hash) : xmur3(hash + tokenId);
  return ${randomMethod};
}

export function generateEdition({ hash, tokenId, curated = false }) {
  if (typeof hash !== 'string' || hash.length === 0 || typeof tokenId !== 'string' || tokenId.length === 0 || typeof curated !== 'boolean') {
    throw new TypeError('Edition a requires nonempty hash and tokenId strings and a boolean curated flag.');
  }
  const $hl = { random: createRandom(hash, tokenId, curated) };
  ${generator}
  ${melodyConstants}
  const S = (${wordFunction})();
  ${melody};
  ${borders}
  const border = i($);
  const pleasantness = S.analysis.vulgarity <= .5;
  return {
    word: S.written.clean,
    pronunciation: S.pronunciation,
    written: S.written,
    syllables: S.syllables,
    analysis: S.analysis,
    melody: E,
    noteCount: C,
    common: S.analysis.isCommon,
    pleasantness,
    border,
    traits: {
      syllables: S.syllables.length,
      complexity: S.analysis.complexity,
      sonority: S.analysis.sonority,
      melodyLength: C,
      border,
      pleasantness,
    },
  };
}
`;

const target = new URL('engine.mjs', directory);
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== module) throw new Error('The edition adapter differs from its reproducible extraction.');
  console.log('Edition a snapshot and adapter match.');
} else {
  await writeFile(target, module);
  console.log(`Wrote ${target.pathname}`);
}
